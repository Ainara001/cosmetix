#!/usr/bin/env python3
"""Builds tools/rights/photo_rights.json and docs/product-photo-rights-audit.md
from assets/products/CREDITS.txt, assets/catalog/products.json and the files.

Run from the repository root:  python3 -I tools/rights/photo_audit.py

Nothing here decides that a picture is allowed. Every product photo is
`not_cleared` until a person records a licence or a written permission in
`tools/rights/photo_rights_overrides.json` (file -> {status, evidence}). A share
build (tools/rights/share_build.sh) leaves out every photo that is not `cleared`.
"""
import hashlib, json, os, re, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
P = lambda *a: os.path.join(ROOT, *a)

products = json.load(open(P('assets/catalog/products.json'), encoding='utf-8'))['products']
by_photo = {}
for i, p in enumerate(products, 1):
    if p.get('photo'):
        by_photo.setdefault(os.path.basename(p['photo']), []).append((i, p['brand'], p['name']))

credits = {}
note_for = {}
for line in open(P('assets/products/CREDITS.txt'), encoding='utf-8'):
    m = re.match(r'\s*(\d+)\.jpg\s+(.*?)\s{2,}(\S.*)$', line.rstrip())
    if m:
        credits[m.group(1) + '.jpg'] = m.group(3).strip()
# the palettes 23-27 say "official shade photos from romandbeauty.com"
official_shop = {f'{n}.jpg' for n in range(23, 28)}

def jpeg_size(path):
    with open(path, 'rb') as f:
        data = f.read()
    i = 2
    while i < len(data):
        if data[i] != 0xFF:
            i += 1; continue
        mk = data[i + 1]
        if 0xC0 <= mk <= 0xCF and mk not in (0xC4, 0xC8, 0xCC):
            h, w = struct.unpack('>HH', data[i + 5:i + 9]); return w, h
        i += 2 + struct.unpack('>H', data[i + 2:i + 4])[0]
    return None, None

overrides = {}
if os.path.exists(P('tools/rights/photo_rights_overrides.json')):
    overrides = json.load(open(P('tools/rights/photo_rights_overrides.json')))

rows = []
for fn in sorted(os.listdir(P('assets/products')), key=lambda s: (len(s), s)):
    if not fn.endswith('.jpg'):
        continue
    path = P('assets/products', fn)
    w, h = jpeg_size(path)
    src = credits.get(fn)
    if fn in official_shop:
        origin = 'romandbeauty.com (official shop of the brand) per CREDITS.txt; the catalog page for ingredients is INCIDecoder'
    elif src and 'costco.com' in src:
        origin = 'retailer page (Costco)'
    elif src:
        origin = 'INCIDecoder product page'
    else:
        origin = 'not recorded'
    ov = overrides.get(fn, {})
    rows.append({
        'file': 'assets/products/' + fn,
        'sha256': hashlib.sha256(open(path, 'rb').read()).hexdigest(),
        'bytes': os.path.getsize(path),
        'width': w, 'height': h,
        'products': [f'{n}: {b} {nm}' for n, b, nm in by_photo.get(fn, [])],
        'source_page': src,
        'image_origin': origin,
        'licence_recorded': ov.get('licence', 'none'),
        'rights_status': ov.get('status', 'not_cleared'),
        'evidence': ov.get('evidence'),
        'share_build': 'included' if ov.get('status') == 'cleared' else 'excluded',
    })

out = {
    'comment': 'Per-file audit of assets/products. rights_status is not_cleared until a licence or a written permission is recorded in photo_rights_overrides.json. Generated by tools/rights/photo_audit.py.',
    'generic_photos': [
        {'file': 'assets/photos/compact.jpg', 'licence': 'CC BY-SA 3.0', 'author': 'Andy Mabbett (Wikimedia Commons)', 'status': 'needs_check', 'why': 'attribution and share-alike are required; whether the app shows the attribution is not verified; derivative/crop conditions not reviewed'},
        {'file': 'assets/photos/cream.jpg', 'licence': 'CC BY-SA 4.0', 'author': 'Gilava graphic (Wikimedia Commons)', 'status': 'needs_check', 'why': 'attribution and share-alike are required; whether the app shows the attribution is not verified'},
        {'file': 'assets/photos/palette.jpg', 'licence': 'Pexels License', 'author': 'pexels.com/photo/1327689', 'status': 'needs_check', 'why': 'licence is known; logos/trademarks visible in the picture were not checked'},
        {'file': 'assets/photos/tube.jpg', 'licence': 'Pexels License', 'author': 'pexels.com/photo/3373746', 'status': 'needs_check', 'why': 'licence is known; logos/trademarks visible in the picture were not checked'},
        {'file': 'assets/photos/perfume.jpg', 'licence': 'Pexels License', 'author': 'pexels.com/photo/264819', 'status': 'needs_check', 'why': 'licence is known; logos/trademarks visible in the picture were not checked'},
        {'file': 'assets/photos/bottle.jpg', 'licence': 'Pexels License', 'author': 'pexels.com/photo/34939732', 'status': 'needs_check', 'why': 'licence is known; logos/trademarks visible in the picture were not checked'},
        {'file': 'assets/photos/banner.jpg', 'licence': 'Pexels License', 'author': 'pexels.com/photo/24602068', 'status': 'needs_check', 'why': 'licence is known; people and logos in the picture were not checked'},
    ],
    'products': rows,
}
json.dump(out, open(P('tools/rights/photo_rights.json'), 'w', encoding='utf-8'), ensure_ascii=False, indent=1)
open(P('tools/rights/photo_rights.json'), 'a').write('\n')

md = ['# Аудит прав на изображения', '',
      'Сгенерировано `tools/rights/photo_audit.py` из `assets/products/CREDITS.txt`, `assets/catalog/products.json` и самих файлов. Скрипт ничего не разрешает: пока в `tools/rights/photo_rights_overrides.json` нет записи о лицензии или письменном разрешении, файл имеет статус `not_cleared`, а в демо-сборку для распространения (`tools/rights/share_build.sh`) не попадает.', '',
      '## Фото товаров (`assets/products/`)', '',
      f'Файлов: {len(rows)}. Подтверждённых прав: {sum(1 for r in rows if r["rights_status"]=="cleared")}.', '',
      '| Файл | Товар(ы) каталога | Размер, px | Откуда взят | Лицензия | Статус | В демо-сборке |', '|---|---|---|---|---|---|---|']
for r in rows:
    prods = '; '.join(x.split(': ', 1)[1] for x in r['products']) or '(нет товара)'
    md.append(f"| {os.path.basename(r['file'])} | {prods} | {r['width']}×{r['height']} | {r['image_origin']} | {r['licence_recorded']} | {r['rights_status']} | {r['share_build']} |")
md += ['', '## Общие фото (`assets/photos/`)', '', '| Файл | Лицензия | Автор / источник | Статус | Что не проверено |', '|---|---|---|---|---|']
for g in out['generic_photos']:
    md.append(f"| {os.path.basename(g['file'])} | {g['licence']} | {g['author']} | {g['status']} | {g['why']} |")
md += ['', '## Что значит статус', '',
       '* `not_cleared`: права не подтверждены. Публичная доступность картинки на сайте не равна разрешению её использовать. Файл остаётся в рабочем проекте, но не входит в сборки для распространения.',
       '* `cleared`: записана лицензия или письменное разрешение (поле `evidence`).',
       '* `needs_check`: лицензия известна, но условия (атрибуция, share-alike, знаки в кадре) не проверены полностью.',
       '', '## Альтернативы для коммерческой демонстрации', '',
       '1. Собственные фотографии физических товаров (снимает владелец, права принадлежат ей).',
       '2. Оригинальные нейтральные иллюстрации (рисуются кодом, без чужих логотипов и упаковки).',
       '3. Нейтральный плейсхолдер для товара, права на фото которого не подтверждены (так сейчас ведёт себя сборка для распространения).',
       '', 'Фотографии и элементы дизайна «Золотого Яблока» не используются.']
open(P('docs/product-photo-rights-audit.md'), 'w', encoding='utf-8').write('\n'.join(md) + '\n')
print('ok', len(rows), 'product photos')
